export const errorCodeText = (code: string) => messages[code] ?? `操作未完成（${code}）。请核对状态。`;
export class AppError extends Error {
  constructor(
    public status: number,
    public code: string,
    public outcome = 'rejected',
    public details: Record<string, unknown> = {},
    public issues: ApiErrorBody['issues'] = [],
  ) {
    super(errorCodeText(code));
    this.name = 'AppError';
  }
  static from(status: number, body?: Partial<ApiErrorBody>) {
    return new AppError(status, body?.code ?? 'request:failed', body?.outcome, body?.details, body?.issues);
  }
}
export const errorText = (error: unknown) =>
  error instanceof AppError ? error.message : '操作未完成，请稍后核对状态。';
export const isConflict = (error: unknown) => error instanceof AppError && [409, 428].includes(error.status);
export const isAbort = (error: unknown) => error instanceof DOMException && error.name === 'AbortError';
